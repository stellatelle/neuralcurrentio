#include <string>
#include <vector>

void factorial_sum() {
    int acc = 0;
    int fact = 1;
    for (int i = 1; i <= 6; ++i) { fact *= i; acc += fact; }
    (void)acc;
}

void is_palindrome() {
    std::string text = "level";
    bool palindrome = true;
    for (std::size_t i = 0; i < text.size() / 2; ++i) {
        if (text[i] != text[text.size() - 1 - i]) { palindrome = false; break; }
    }
    (void)palindrome;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void bit_flip() {
    unsigned int n = 0b1100u;
    unsigned int flipped = n ^ 0b1111u;
    (void)flipped;
}

extern "C" int amber_grove();
extern "C" void cedar_meadow();
extern "C" void placid_boulder();
extern "C" void vivid_summit();

int main() {
    factorial_sum();
    is_palindrome();
    text_contains();
    bit_flip();
    cedar_meadow();
    placid_boulder();
    vivid_summit();
    return amber_grove();
}
